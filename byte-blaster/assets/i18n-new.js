// ===============================================
//  INTERNATIONALIZATION (i18n) — Folder-based loader
// ===============================================
// All translations live in the top-level "localisation/" folder, one JSON
// file per language (e.g. en.json, ru.json). To add a new language you only
// need to drop a new <code>.json file into that folder — it is discovered
// automatically (no code changes, no list to edit).
//
// Discovery order:
//   1. Electron  — window.localeAPI.list() reads the folder directly, so a
//      newly-added file shows up on the next launch with zero config.
//   2. Web       — fetch "localisation/index.json" (a manifest array of codes,
//      regenerated by build-html.js so the web build stays in sync).
//   3. Fallback  — probe a small built-in set so the game never starts blank.
//
// Dynamic strings use {0}, {1}, … placeholders, filled by window.t(key, ...args).

(function () {
  'use strict';

  const DIR = 'localisation';
  const FALLBACK_CODES = ['en', 'ru'];

  // Flag emoji per language code, shown to the LEFT of the language name in the
  // settings picker. Keyed by locale code so it works regardless of each file's
  // own langName. Unknown codes fall back to a generic globe.
  const FLAGS = {
    en: '🇬🇧', ru: '🇷🇺',
    'zh-CN': '🇨🇳', 'zh-TW': '🇹🇼', hi: '🇮🇳', es: '🇪🇸', fr: '🇫🇷', ar: '🇸🇦',
    bn: '🇧🇩', pt: '🇵🇹', ja: '🇯🇵', be: '🇧🇾', uk: '🇺🇦', kk: '🇰🇿', de: '🇩🇪',
    tr: '🇹🇷', ko: '🇰🇷', ur: '🇵🇰', it: '🇮🇹', hu: '🇭🇺',
    et: '🇪🇪', lt: '🇱🇹', lv: '🇱🇻', hy: '🇦🇲', ka: '🇬🇪', az: '🇦🇿', uz: '🇺🇿',
    tg: '🇹🇯', ky: '🇰🇬', tk: '🇹🇲',
    pl: '🇵🇱', he: '🇮🇱', nl: '🇳🇱', el: '🇬🇷', ro: '🇷🇴', th: '🇹🇭', vi: '🇻🇳',
    id: '🇮🇩', fil: '🇵🇭',
  };
  window.langFlag = function (code) { return FLAGS[code] || '🌐'; };

  let LANG = 'en';
  let LOCALES = {};          // code -> { key: string }
  let CURRENT = {};          // active language strings
  let LOADED = false;        // have the locale files finished loading?
  let PENDING_LANG = null;   // a setLanguage() request that arrived before load

  // Work out which locale files exist, without hard-coding the list.
  async function discoverCodes() {
    // 1) Electron — real directory listing.
    try {
      if (window.localeAPI && typeof window.localeAPI.list === 'function') {
        const codes = await window.localeAPI.list();
        if (Array.isArray(codes) && codes.length) return codes;
      }
    } catch (e) { /* fall through */ }

    // 2) Web — optional manifest.
    try {
      const res = await fetch(`${DIR}/index.json`);
      if (res.ok) {
        const list = await res.json();
        if (Array.isArray(list) && list.length) return list;
        if (list && Array.isArray(list.languages) && list.languages.length) return list.languages;
      }
    } catch (e) { /* fall through */ }

    // 3) Last resort.
    return FALLBACK_CODES.slice();
  }

  // Load one locale: Electron via IPC (works under file://), web via fetch.
  async function loadOne(code) {
    if (window.localeAPI && typeof window.localeAPI.read === 'function') {
      const data = await window.localeAPI.read(code);
      if (data) return data;
    }
    const res = await fetch(`${DIR}/${code}.json`);
    if (res.ok) return await res.json();
    return null;
  }

  async function loadLocales() {
    const codes = await discoverCodes();

    for (const code of codes) {
      try {
        const data = await loadOne(code);
        if (data) {
          LOCALES[code] = data;
          console.log(`✔ Loaded locale: ${code}`);
        }
      } catch (e) {
        console.warn(`Failed to load locale ${code}:`, e);
      }
    }

    if (!LOCALES.en && Object.keys(LOCALES).length === 0) {
      console.warn('No locale files loaded — UI will show raw keys.');
    }

    // Pick the active language: saved preference → system language → en.
    let sys = 'en';
    try { sys = (navigator.language || 'en').toLowerCase().startsWith('ru') ? 'ru' : 'en'; } catch (e) {}

    let saved = 'auto';
    try {
      const s = JSON.parse(localStorage.getItem('bbSettings') || '{}');
      if (s && s.language) saved = s.language;
    } catch (e) {}

    LANG = (saved === 'auto' || !saved) ? sys : saved;
    if (!LOCALES[LANG]) {
      console.warn(`Language "${LANG}" unavailable, falling back.`);
      LANG = LOCALES.en ? 'en' : (Object.keys(LOCALES)[0] || 'en');
    }
    CURRENT = LOCALES[LANG] || {};
    console.log(`✔ Active language: ${LANG} (available: ${Object.keys(LOCALES).join(', ')})`);
  }

  // Translate a key, filling {0}, {1}, … with the supplied args.
  window.t = function (key, ...args) {
    let str = CURRENT[key];
    if (str === undefined && LANG !== 'en' && LOCALES.en) str = LOCALES.en[key];
    if (str === undefined) return key; // graceful: show the key itself
    if (typeof str === 'function') return str(...args); // (not used by JSON, kept for safety)
    if (args.length && typeof str === 'string') {
      return str.replace(/\{(\d+)\}/g, (m, i) => (args[i] !== undefined ? args[i] : m));
    }
    return str;
  };

  window.i18nLang = function () { return LANG; };
  // Raw access to the active language's full string table — used for structured
  // data (cutscene dialogue) that can't go through the per-key t() helper.
  // Returns the English table as a fallback so callers always get something.
  window.i18nRaw = function () { return CURRENT || LOCALES.en || {}; };
  window.i18nRawEn = function () { return LOCALES.en || {}; };

  // English (reference) name per language code. Shown in parentheses after the
  // native name in the picker — e.g. "Русский (Russian)" — so a language is
  // recognisable no matter what language the UI is currently in. Centralised
  // here so it stays correct without editing every locale file.
  const ENGLISH_NAMES = {
    en: 'English', ru: 'Russian',
    'zh-CN': 'Chinese Simplified', 'zh-TW': 'Chinese Traditional', hi: 'Hindi',
    es: 'Spanish', fr: 'French', ar: 'Arabic', bn: 'Bengali', pt: 'Portuguese',
    ja: 'Japanese', be: 'Belarusian', uk: 'Ukrainian', kk: 'Kazakh', de: 'German',
    tr: 'Turkish', ko: 'Korean', ur: 'Urdu', it: 'Italian', hu: 'Hungarian',
    et: 'Estonian', lt: 'Lithuanian', lv: 'Latvian', hy: 'Armenian', ka: 'Georgian',
    az: 'Azerbaijani', uz: 'Uzbek', tg: 'Tajik', ky: 'Kyrgyz', tk: 'Turkmen',
    pl: 'Polish', he: 'Hebrew', nl: 'Dutch', el: 'Greek', ro: 'Romanian',
    th: 'Thai', vi: 'Vietnamese', id: 'Indonesian', fil: 'Filipino',
  };
  window.langEnglishName = function (code) { return ENGLISH_NAMES[code] || ''; };

  // Languages available for the picker: [{ code, name }] where name is
  // "Native (English)" (or just the native name when they're identical).
  window.getAvailableLanguages = function () {
    return Object.keys(LOCALES).map(code => {
      const native = (LOCALES[code] && LOCALES[code].langName) || code.toUpperCase();
      const eng = ENGLISH_NAMES[code] || '';
      const name = (eng && eng !== native) ? `${native} (${eng})` : native;
      return { code, name };
    });
  };

  function applyDOM() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      el.textContent = window.t(el.getAttribute('data-i18n'));
    });
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      el.innerHTML = window.t(el.getAttribute('data-i18n-html'));
    });
    // Localised input placeholders (data-i18n-ph="key")
    document.querySelectorAll('[data-i18n-ph]').forEach(el => {
      el.setAttribute('placeholder', window.t(el.getAttribute('data-i18n-ph')));
    });
  }
  window.applyI18nDOM = applyDOM;

  window.setLanguage = function (lang) {
    // Requests can arrive before the async locale load finishes (e.g. settings.js
    // applies the saved language on startup). Queue it and apply once loaded.
    if (!LOADED) { PENDING_LANG = lang; return; }
    if (!LOCALES[lang]) { console.warn(`Language "${lang}" not available`); return; }
    LANG = lang;
    CURRENT = LOCALES[lang];
    try {
      const s = JSON.parse(localStorage.getItem('bbSettings') || '{}');
      s.language = LANG;
      localStorage.setItem('bbSettings', JSON.stringify(s));
    } catch (e) {}
    if (window.gameSettings) window.gameSettings.language = LANG;
    applyDOM();
    if (typeof window.refreshDynamicUI === 'function') window.refreshDynamicUI();
    if (typeof window.refreshLanguagePicker === 'function') window.refreshLanguagePicker();
    document.documentElement.lang = LANG;
    console.log(`✔ Language changed to: ${LANG}`);
  };

  // Load locales, then translate the DOM and let the rest of the UI know.
  loadLocales().then(() => {
    LOADED = true;
    // Apply any language request that arrived before loading finished.
    if (PENDING_LANG) {
      const want = PENDING_LANG; PENDING_LANG = null;
      if (LOCALES[want]) { LANG = want; CURRENT = LOCALES[want]; }
    }
    const done = () => {
      applyDOM();
      document.documentElement.lang = LANG;
      if (typeof window.refreshLanguagePicker === 'function') window.refreshLanguagePicker();
    };
    if (document.readyState === 'loading') {
      document.addEventListener('DOMContentLoaded', done);
    } else {
      done();
    }
  });

  console.log('✅ i18n system loaded (folder-based loader)');
})();
