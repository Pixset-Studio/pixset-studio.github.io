-- функцию, а звалась бы другая.
--
-- Оставляем ту, у которой есть p_limit. Старые вызовы с одним p_query попадут
-- в неё же — значение по умолчанию их подхватит.
--
-- Применить: Supabase → SQL Editor → выполнить целиком.

